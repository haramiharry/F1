-- =============================================================================
-- Manual Migration: Partial Unique Index for predictions (model source)
-- =============================================================================
-- Purpose:
--   Enforce database-level uniqueness on active model predictions.
--   Only one active model prediction should exist per (car_id, circuit_id,
--   prediction_type) combination at any time. The source_type='model' filter
--   excludes editorial baselines (round_valid_from=0), which can coexist with
--   superseded model predictions for audit purposes.
--
--   superseded_at IS NULL selects only the current (non-superseded) record.
--   source_type = 'model' targets model predictions exclusively.
--   Editorial predictions (source_type='editorial') and hybrid predictions
--   (source_type='hybrid') are excluded — they have separate governance rules.
--
-- Why this is a manual migration (not generated by Prisma):
--   The Prediction model has no @@unique in the Prisma schema because:
--   1. Prisma does not support partial unique indexes natively.
--   2. A full @@unique would block the amendment chain (new supersedes old).
--   This SQL is the sole DB-level uniqueness guard for active model predictions.
--
-- Application-layer responsibility:
--   The prediction engine must check for an existing active model prediction
--   before inserting a new one. When one exists, it creates the new record
--   and supersedes the old (amendment chain), never overwrites.
--
-- How to apply:
--   After running `npx prisma migrate dev`, execute:
--     sqlite3 ./prisma/dev.db < ./prisma/manual/003_predictions_partial_unique.sql
--   For PostgreSQL (production):
--     psql $DATABASE_URL -f ./prisma/manual/003_predictions_partial_unique.sql
-- =============================================================================

-- SQLite version (development)
-- Note: SQLite does not support partial indexes on expressions with string
-- comparison in older versions. SQLite 3.8.9+ supports WHERE with string literals.
CREATE UNIQUE INDEX IF NOT EXISTS idx_predictions_model_active_unique
  ON predictions (car_id, circuit_id, prediction_type)
  WHERE superseded_at IS NULL AND source_type = 'model';

